export function officialLoanSeeds(country: LoanCountry, loanType: LoanType): LoanResult[] {
  return OFFICIAL_LOAN_PAGES.filter((item) => item.country === country && item.loanType === loanType)
}

export function tavilyLoanIncludeDomains(country: LoanCountry, loanType: LoanType): string[] {
  return [...TAVILY_INCLUDE[country][loanType]]
}

export function isGovernmentLoanHost(hostname: string): boolean {
  const host = hostname.replace(/^www\./i, "").toLowerCase()
  return (
    host.endsWith(".gov") ||
    host.endsWith(".gc.ca") ||
    host === "canada.ca" ||
    host.endsWith(".canada.ca") ||
    host === "ontario.ca" ||
    host.endsWith(".ontario.ca") ||
    host === "quebec.ca" ||
    host.endsWith(".quebec.ca") ||
    host === "studentaidbc.ca" ||
    host.endsWith(".studentaidbc.ca") ||
    host === "studentaid.alberta.ca" ||
    host === "saskatchewan.ca" ||
    host.endsWith(".saskatchewan.ca") ||
    host === "novascotia.ca" ||
    host.endsWith(".novascotia.ca")
  )
}
